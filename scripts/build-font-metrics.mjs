#!/usr/bin/env node
/**
 * Regenerates the character width tables in
 * src/core/font_metrics.generated.ts by measuring the app's three font
 * families (regular and bold) with Canvas 2D `measureText` in headless Google Chrome (DevTools
 * Protocol, no dependencies).
 *
 * Usage: node scripts/build-font-metrics.mjs [path-to-chrome]
 *
 * Widths are advances at 1px font size for printable ASCII and Latin-1
 * letters, so text can be measured and wrapped identically in the canvas
 * renderer, the SVG export and the MCP server (Node, no canvas). Run
 * `pnpm lint` afterwards to format the generated module.
 */
import { spawn } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CHROME =
  process.argv[2] ??
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'core',
  'font_metrics.generated.ts',
);

/** Table key → CSS font measured (see tableFor in text_metrics.ts). */
const FONTS = {
  sans: 'Arial',
  sansBold: 'bold Arial',
  serif: 'Georgia',
  serifBold: 'bold Georgia',
  mono: '"Courier New"',
  monoBold: 'bold "Courier New"',
};
/** Code points 32..126 and 160..255. */
const CODES = [
  ...Array.from({ length: 95 }, (_, i) => 32 + i),
  ...Array.from({ length: 96 }, (_, i) => 160 + i),
];
const SIZE = 1000;

const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const port = 9400 + Math.floor(Math.random() * 400);
const chrome = spawn(
  CHROME,
  [
    '--headless=new',
    `--remote-debugging-port=${port}`,
    `--user-data-dir=${mkdtempSync(join(tmpdir(), 'markasso-metrics-'))}`,
    'about:blank',
  ],
  { stdio: 'ignore' },
);
try {
  let target;
  for (let i = 0; i < 50 && !target; i++) {
    await wait(200);
    try {
      const list = await (await fetch(`http://127.0.0.1:${port}/json`)).json();
      target = list.find((t) => t.type === 'page');
    } catch {
      // Chrome not listening yet.
    }
  }
  if (!target) throw new Error('Chrome did not start');
  const ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((r) => ws.addEventListener('open', r));
  const expression = `(() => {
    const ctx = document.createElement('canvas').getContext('2d');
    const out = {};
    for (const [key, font] of Object.entries(${JSON.stringify(FONTS)})) {
      const [weight, family] = font.startsWith('bold ')
        ? ['bold ', font.slice(5)]
        : ['', font];
      ctx.font = weight + '${SIZE}px ' + family;
      out[key] = ${JSON.stringify(CODES)}.map(
        (c) => Math.round(ctx.measureText(String.fromCharCode(c)).width) / ${SIZE},
      );
    }
    return out;
  })()`;
  const result = await new Promise((resolve) => {
    ws.addEventListener('message', (e) => resolve(JSON.parse(e.data)));
    ws.send(
      JSON.stringify({
        id: 1,
        method: 'Runtime.evaluate',
        params: { expression, returnByValue: true },
      }),
    );
  });
  ws.close();
  const tables = result.result.result.value;
  const body = Object.entries(tables)
    .map(([key, widths]) => `  ${key}: [${widths.join(', ')}],`)
    .join('\n');
  await writeFile(
    OUT,
    `// Generated by scripts/build-font-metrics.mjs. Do not edit by hand.

/** Advance widths at 1px font size for code points 32..126, then 160..255. */
export const FONT_WIDTHS = {
${body}
} as const;
`,
  );
  console.log(`Wrote ${OUT}`);
} finally {
  chrome.kill();
}
